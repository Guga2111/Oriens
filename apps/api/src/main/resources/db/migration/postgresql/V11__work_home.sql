-- Account-owned home links and actual opens, independent of domain resource versions.
CREATE TABLE work_quick_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name varchar(80) NOT NULL CHECK (length(btrim(name)) > 0),
    url varchar(2048) NOT NULL CHECK (length(btrim(url)) > 0),
    created_at timestamptz NOT NULL,
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX idx_home_links_owner ON work_quick_links(user_id, created_at, id);
CREATE TABLE work_recent_visits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    task_id bigint,
    project_id bigint,
    visited_at timestamptz NOT NULL,
    CHECK ((task_id IS NOT NULL AND project_id IS NULL) OR (task_id IS NULL AND project_id IS NOT NULL)),
    UNIQUE(user_id, task_id),
    UNIQUE(user_id, project_id),
    FOREIGN KEY(task_id, user_id) REFERENCES tasks(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY(project_id, user_id) REFERENCES project(id, user_id) ON DELETE CASCADE
);
CREATE INDEX idx_home_visits_owner ON work_recent_visits(user_id, visited_at DESC, id DESC);
