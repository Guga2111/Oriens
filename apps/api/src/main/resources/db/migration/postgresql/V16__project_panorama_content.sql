ALTER TABLE project ADD COLUMN description_doc jsonb;

CREATE TABLE project_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    kind varchar(32) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    subject_id bigint,
    subject_title varchar(200)
);

CREATE INDEX idx_project_activity_feed ON project_activity (project_id, occurred_at DESC, id DESC);

-- A rolled-back API can still update the text projection.
CREATE FUNCTION clear_stale_project_description_doc() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.description IS DISTINCT FROM OLD.description
       AND NEW.description_doc IS NOT DISTINCT FROM OLD.description_doc THEN
        NEW.description_doc := NULL;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER project_description_legacy_write
    BEFORE UPDATE OF description ON project FOR EACH ROW
    EXECUTE FUNCTION clear_stale_project_description_doc();
