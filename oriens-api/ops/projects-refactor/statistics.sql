  parent_entry_id bigint NOT NULL REFERENCES financial_entry(id) ON DELETE RESTRICT,
  entry_date date NOT NULL,
  entry_id bigint UNIQUE REFERENCES financial_entry(id) ON DELETE SET NULL,
