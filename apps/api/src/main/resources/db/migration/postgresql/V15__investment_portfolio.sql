-- Manual investment portfolio (objective #8, task #119). Additive: existing entries stay STANDARD.

-- The predefined Investimentos tag is identified by a stable key, never by its (renamable) name.
ALTER TABLE tags ADD COLUMN system_key varchar(32);
ALTER TABLE tags ADD CONSTRAINT tags_system_key_check CHECK (system_key IS NULL OR system_key = 'INVESTMENTS');
CREATE UNIQUE INDEX uq_tags_user_system_key ON tags(user_id, system_key) WHERE system_key IS NOT NULL;
-- UNIQUE(user_id,name) leaves at most one "Investimentos" per account: adopt it, default or custom.
UPDATE tags SET system_key = 'INVESTMENTS' WHERE name = 'Investimentos';
INSERT INTO tags(user_id, name, color, is_default, allow_negative, created_at, system_key)
SELECT u.id, 'Investimentos', '#8B5CF6', true, true, now(), 'INVESTMENTS' FROM users u
WHERE NOT EXISTS (SELECT 1 FROM tags t WHERE t.user_id = u.id AND t.system_key = 'INVESTMENTS');

-- Explicit cash classification. Transfers move the balance, never income or expenses.
ALTER TABLE financial_entry ADD COLUMN kind varchar(32) NOT NULL DEFAULT 'STANDARD';
ALTER TABLE financial_entry ADD CONSTRAINT financial_entry_kind_check
    CHECK (kind IN ('STANDARD', 'INVESTMENT_TRANSFER', 'INVESTMENT_INCOME'));

CREATE TABLE investments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name varchar(120) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    asset_class varchar(32) NOT NULL CHECK (asset_class IN ('FIXED_INCOME', 'STOCKS', 'REAL_ESTATE_FUNDS', 'OTHER')),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    UNIQUE (id, user_id)
);
CREATE INDEX idx_investments_user ON investments(user_id, lower(name), id);

-- One sequence orders valuations and movements recorded on the same calendar day.
CREATE SEQUENCE investment_record_seq;

CREATE TABLE investment_valuations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    investment_id bigint NOT NULL,
    valued_on date NOT NULL,
    amount numeric(12,2) NOT NULL CHECK (amount >= 0),
    recorded_seq bigint NOT NULL DEFAULT nextval('investment_record_seq'),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    FOREIGN KEY (investment_id, user_id) REFERENCES investments(id, user_id) ON DELETE CASCADE
);
CREATE INDEX idx_investment_valuations_latest ON investment_valuations(user_id, investment_id, valued_on DESC, recorded_seq DESC);

CREATE TABLE investment_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    investment_id bigint NOT NULL,
    type varchar(32) NOT NULL CHECK (type IN ('CONTRIBUTION', 'WITHDRAWAL', 'INCOME')),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    occurred_on date NOT NULL,
    description varchar(255),
    entry_id bigint NOT NULL UNIQUE,
    recorded_seq bigint NOT NULL DEFAULT nextval('investment_record_seq'),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    FOREIGN KEY (investment_id, user_id) REFERENCES investments(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (entry_id, user_id) REFERENCES financial_entry(id, user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_investment_movements_investment ON investment_movements(investment_id, occurred_on);
CREATE INDEX idx_investment_movements_user_date ON investment_movements(user_id, occurred_on DESC, id DESC);
