CREATE TABLE habits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  name varchar(100) NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 100),
  created_on date NOT NULL, start_date date NOT NULL, end_date date,
  archived_on date, version bigint NOT NULL DEFAULT 0 CHECK(version>=0),
  UNIQUE(id,user_id), CHECK(start_date>=created_on), CHECK(end_date IS NULL OR end_date>=start_date)
);
CREATE INDEX idx_habits_owner ON habits(user_id,id);
CREATE TABLE habit_schedules (
  habit_id bigint NOT NULL, user_id bigint NOT NULL,
  start_date date NOT NULL, end_date date,
  weekdays integer NOT NULL CHECK(weekdays BETWEEN 1 AND 127),
  PRIMARY KEY(habit_id,start_date),
  FOREIGN KEY(habit_id,user_id) REFERENCES habits(id,user_id) ON DELETE RESTRICT,
  CHECK(end_date IS NULL OR end_date>=start_date)
);
CREATE UNIQUE INDEX uq_habit_open_schedule ON habit_schedules(habit_id) WHERE end_date IS NULL;
CREATE TABLE habit_pauses (
  habit_id bigint NOT NULL, user_id bigint NOT NULL, start_date date NOT NULL, end_date date NOT NULL,
  PRIMARY KEY(habit_id,start_date),
  FOREIGN KEY(habit_id,user_id) REFERENCES habits(id,user_id) ON DELETE RESTRICT,
  CHECK(end_date>=start_date)
);
CREATE TABLE habit_executions (
  habit_id bigint NOT NULL, user_id bigint NOT NULL, execution_date date NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT current_timestamp,
  PRIMARY KEY(habit_id,execution_date),
  FOREIGN KEY(habit_id,user_id) REFERENCES habits(id,user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_habit_execution_period ON habit_executions(user_id,execution_date,habit_id);
