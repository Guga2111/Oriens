// Full label lifecycle against the disposable JWT/JPA/PostgreSQL API, no mocked work endpoints.
import { chromium } from '../../../apps/client/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const [base, project, linked, standalone] = process.argv.slice(2);
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser' });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 900 }, timezoneId: 'Pacific/Auckland', reducedMotion: 'reduce' });
  page.setDefaultTimeout(12000);
  await page.clock.setFixedTime(new Date('2026-11-13T12:00:00Z'));
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const labelPicker = () => page.locator('#task-labels');
  const saveTask = async id => {
    const response = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().endsWith(`/task/${id}`));
    await page.getByRole('button', { name: 'Salvar tarefa', exact: true }).click();
    const result = await response; assert.equal(result.status(), 200);
    await page.getByRole('dialog', { name: 'Editar tarefa', exact: true }).waitFor({ state: 'hidden' });
    return (await result.json()).task;
  };
  const editDayTask = async id => {
    const row = page.locator(`#task-row-${id}`);
    await row.getByRole('button', { name: /^Ações da tarefa/ }).click();
    await page.getByRole('menuitem', { name: 'Editar', exact: true }).click();
    await page.getByRole('dialog', { name: 'Editar tarefa', exact: true }).waitFor();
  };
  await page.goto(`${base}/tasks/project/${project}`);
  await page.getByRole('button', { name: 'Montar formulário', exact: true }).click();
  await labelPicker().click();
  await page.getByRole('button', { name: 'Criar etiqueta', exact: true }).click();
  await page.getByLabel('Nome da etiqueta', { exact: true }).fill('Entrega');
  await page.getByRole('radio', { name: 'Verde', exact: true }).click();
  const creation = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/task-labels/user/'));
  await page.getByRole('button', { name: 'Salvar etiqueta', exact: true }).click();
  const created = await creation; assert.equal(created.status(), 201); const label = await created.json();
  await page.getByRole('button', { name: 'Remover etiqueta Entrega desta tarefa', exact: true }).waitFor();
  const saved = await saveTask(linked); assert.deepEqual(saved.labels.map(l => l.id), [label.id]);
  await page.goto(`${base}/tasks?date=2026-11-13`);
  await page.locator(`#task-row-${linked}`).getByText('Entrega', { exact: true }).waitFor();
  await editDayTask(standalone); await labelPicker().click();
  await page.getByRole('checkbox', { name: 'Entrega', exact: true }).check();
  await page.keyboard.press('Escape');
  const free = await saveTask(standalone); assert.equal(free.projectId, null); assert.equal(free.labels[0].id, label.id);
  await editDayTask(standalone); await labelPicker().click();
  await page.getByRole('button', { name: 'Editar etiqueta Entrega', exact: true }).click();
  await page.getByLabel('Nome da etiqueta', { exact: true }).fill('Publicação');
  const rename = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith(`/task-labels/${label.id}`));
  await page.getByRole('button', { name: 'Salvar etiqueta', exact: true }).click(); assert.equal((await rename).status(), 200);
  await page.getByRole('dialog', { name: 'Editar etiqueta', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.locator(`#task-row-${linked}`).getByText('Publicação', { exact: true }).waitFor();
  await page.locator(`#task-row-${standalone}`).getByText('Publicação', { exact: true }).waitFor();
  await page.goto(`${base}/tasks/project/${project}`);
  await page.getByText('Publicação', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Montar formulário', exact: true }).click(); await labelPicker().click();
  await page.getByRole('button', { name: 'Editar etiqueta Publicação', exact: true }).click();
  await page.getByRole('button', { name: 'Excluir etiqueta', exact: true }).click();
  const confirmation = page.getByRole('alertdialog'); await confirmation.getByText(/todas as suas tarefas/).waitFor();
  const deletion = page.waitForResponse(r => r.request().method() === 'DELETE' && r.url().endsWith(`/task-labels/${label.id}`));
  await confirmation.getByRole('button', { name: 'Excluir etiqueta', exact: true }).click(); assert.equal((await deletion).status(), 204);
  await confirmation.waitFor({ state: 'hidden' });
  await page.getByRole('dialog', { name: 'Editar etiqueta', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('dialog', { name: 'Editar tarefa', exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('alertdialog').count(), 0, 'committed label deletion is not an unsaved task edit');
  await page.goto(`${base}/tasks?date=2026-11-13`);
  await page.locator(`#task-row-${linked}`).waitFor();
  assert.equal(await page.getByText('Publicação', { exact: true }).count(), 0);
  assert.equal(await page.locator(`#task-row-${standalone}`).getByRole('checkbox').getAttribute('aria-checked'), 'false');
  assert.deepEqual(errors, []);
  console.log('PASS labels live: create → link project/standalone → day/board → rename everywhere → confirm global delete; IDs/states/dates preserved.');
} finally { await browser.close(); }
