ALTER TABLE tasks ADD CONSTRAINT uq_tasks_label_owner UNIQUE (id, user_id);
CREATE TABLE task_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name varchar(50) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 50),
    color varchar(16) NOT NULL CHECK (color IN ('RED','ORANGE','YELLOW','GREEN','BLUE','GRAY')),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE (id, user_id)
);
CREATE UNIQUE INDEX uq_task_labels_owner_name ON task_labels(user_id, lower(name));
CREATE TABLE task_label_assignments (
    task_id bigint NOT NULL,
    label_id bigint NOT NULL,
    user_id bigint NOT NULL,
    PRIMARY KEY(task_id, label_id),
    CONSTRAINT fk_task_label_task_owner FOREIGN KEY(task_id,user_id)
        REFERENCES tasks(id,user_id) ON DELETE CASCADE,
    CONSTRAINT fk_task_label_label_owner FOREIGN KEY(label_id,user_id)
        REFERENCES task_labels(id,user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_task_label_assignments_label ON task_label_assignments(user_id,label_id,task_id);
