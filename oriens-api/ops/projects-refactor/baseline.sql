-- oriens-projects-v2 / PostgreSQL 15+. Explicit installation only; not a Flyway migration.
-- db.py supplies the transaction, empty-database guard, checksum and schema seal.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL, email varchar(255) NOT NULL,
    password varchar(255) NOT NULL, profile_image_url varchar(255), phone_number varchar(255),
    notifications boolean, sound boolean, theme varchar(255),
    created_at timestamp(6) NOT NULL,
    role varchar(255) NOT NULL CHECK (role::text = ANY (ARRAY['USER','ADMIN']::text[]))
);
CREATE SEQUENCE password_reset_token_seq START WITH 1 INCREMENT BY 50;
CREATE TABLE password_reset_token (
    id bigint PRIMARY KEY, token varchar(255) NOT NULL UNIQUE,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    expiry_date timestamp(6) NOT NULL
);
CREATE TABLE tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name varchar(50) NOT NULL, color varchar(7) NOT NULL,
    is_default boolean NOT NULL, allow_negative boolean NOT NULL,
    created_at timestamp(6) NOT NULL, UNIQUE(user_id,name)
);
CREATE TABLE financial_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    amount numeric(12,2) NOT NULL, entry_date date NOT NULL,
    description varchar(255) NOT NULL, created_at timestamp(6) NOT NULL,
    updated_at timestamp(6), tag_id bigint NOT NULL REFERENCES tags(id) ON DELETE RESTRICT,
    is_recurring boolean NOT NULL, recurrence_end_date date, parent_entry_id bigint,
    recurrence_pattern varchar(255) CHECK (recurrence_pattern::text = ANY (ARRAY['DAILY','WEEKLY','BIWEEKLY','MONTHLY','QUARTERLY','SEMIANNUALLY','YEARLY']::text[]))
);
CREATE INDEX idx_is_recurring ON financial_entry(is_recurring);
CREATE INDEX idx_parent_entry ON financial_entry(parent_entry_id);
CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    message varchar(255) NOT NULL, is_read boolean NOT NULL,
    link_to varchar(255), created_at timestamp(6) NOT NULL
);
CREATE TABLE support_tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    subject varchar(255) NOT NULL, message text NOT NULL, user_email varchar(255) NOT NULL,
    status varchar(255) NOT NULL CHECK (status::text = ANY (ARRAY['OPEN','IN_PROGRESS','CLOSED']::text[])),
    priority varchar(255) CHECK (priority::text = ANY (ARRAY['LOW','MEDIUM','HIGH']::text[])),
    created_at timestamp(6) NOT NULL, updated_at timestamp(6)
);
CREATE TABLE project (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    description varchar(10000), color varchar(255), image_url varchar(255),
    mode varchar(20) NOT NULL CHECK (mode::text = ANY (ARRAY['SIMPLE','DEVELOPMENT']::text[])),
    is_favorite boolean NOT NULL DEFAULT false, archived boolean NOT NULL DEFAULT false,
    last_accessed timestamp(6) with time zone,
    default_pending_column_id bigint, default_completed_column_id bigint,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE(id,user_id),
    CHECK (mode <> 'SIMPLE' OR
      (default_pending_column_id IS NULL AND default_completed_column_id IS NULL))
);
CREATE TABLE project_objectives (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE RESTRICT,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    due_date date, status varchar(20) NOT NULL DEFAULT 'PENDING'
      CHECK (status::text = ANY (ARRAY['PENDING','CONCLUDED']::text[])),
    position integer NOT NULL CHECK (position >= 0),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0), UNIQUE(id,project_id)
);
CREATE INDEX idx_objectives_order ON project_objectives(project_id,position,id);
CREATE TABLE project_columns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE RESTRICT,
    name varchar(60) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
    kind varchar(20) NOT NULL CHECK (kind::text = ANY (ARRAY['PENDING','ON_DOING','CONCLUDED','CANCELLED']::text[])),
    position integer NOT NULL CHECK (position >= 0),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE(id,project_id), UNIQUE(id,project_id,kind)
);
CREATE UNIQUE INDEX uq_column_name ON project_columns(project_id,lower(btrim(name)));
CREATE INDEX idx_columns_order ON project_columns(project_id,position,id);
-- Nullable during atomic construction/removal. Services validate kind and required defaults
-- at commit, under project lock; immediate NOT NULL/CHECK would obstruct that transaction.
ALTER TABLE project ADD CONSTRAINT fk_default_pending
    FOREIGN KEY(default_pending_column_id,id) REFERENCES project_columns(id,project_id) ON DELETE RESTRICT;
ALTER TABLE project ADD CONSTRAINT fk_default_completed
    FOREIGN KEY(default_completed_column_id,id) REFERENCES project_columns(id,project_id) ON DELETE RESTRICT;
CREATE TABLE tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    project_id bigint, objective_id bigint, column_id bigint, position integer,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    description varchar(10000), planned_date date, start_time time(0), due_date date,
    priority varchar(255) NOT NULL DEFAULT 'MEDIUM' CHECK (priority::text = ANY (ARRAY['LOW','MEDIUM','HIGH']::text[])),
    status varchar(255) NOT NULL DEFAULT 'PENDING'
      CHECK (status::text = ANY (ARRAY['PENDING','ON_DOING','CONCLUDED','CANCELLED']::text[])),
    completed_at date, created_at timestamp(6) with time zone NOT NULL,
    address varchar(255), latitude double precision, longitude double precision,
    reminder_sent boolean NOT NULL DEFAULT false, overdue_notification_sent boolean NOT NULL DEFAULT false,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT fk_task_project_owner FOREIGN KEY(project_id,user_id)
      REFERENCES project(id,user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_objective FOREIGN KEY(objective_id,project_id)
      REFERENCES project_objectives(id,project_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_column_status FOREIGN KEY(column_id,project_id,status)
      REFERENCES project_columns(id,project_id,kind) ON DELETE RESTRICT,
    CHECK ((project_id IS NULL AND objective_id IS NULL AND column_id IS NULL AND position IS NULL)
      OR (project_id IS NOT NULL AND column_id IS NOT NULL AND position IS NOT NULL AND position >= 0)),
    CHECK (start_time IS NULL OR (planned_date IS NOT NULL AND start_time < time '24:00:00')),
    CHECK ((status = 'CONCLUDED') = (completed_at IS NOT NULL))
);
CREATE INDEX idx_tasks_planning ON tasks(user_id,planned_date,status,start_time);
CREATE INDEX idx_tasks_deadline ON tasks(user_id,due_date,status);
CREATE INDEX idx_tasks_board ON tasks(project_id,column_id,position,id);
CREATE INDEX idx_tasks_objective ON tasks(objective_id);
-- No FK to resource_id: retain the receipt after deletion so retries return 410.
CREATE TABLE creation_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operation varchar(200) NOT NULL, idempotency_key uuid NOT NULL,
    payload_sha256 varchar(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    resource_id bigint NOT NULL, response_status integer NOT NULL CHECK (response_status = 201),
    response_body jsonb NOT NULL, resource_version bigint NOT NULL CHECK (resource_version >= 0),
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    CHECK (expires_at >= created_at + interval '24 hours'),
    UNIQUE(user_id,operation,idempotency_key)
);
CREATE INDEX idx_receipts_expiry ON creation_receipts(expires_at);
